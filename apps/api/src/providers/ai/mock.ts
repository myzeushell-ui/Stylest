// MockAIProvider — правдоподобный стайлинг-ассистент без обращения к внешним API.
// Работает офлайн и бесплатно. Главное: ВСЕГДА объясняет «почему», как и
// требует продукт. Ответы строятся по ключевым словам последнего вопроса.

import type { AIProvider, AIChatRequest, AIChatResponse } from './types.js';

const reply = (lastUser: string): string => {
  const q = lastUser.toLowerCase();

  if (q.includes('дороже') || q.includes('докупить'))
    return (
      'Чтобы выглядеть дороже, делай ставку на спокойную палитру и хорошую посадку.\n\n' +
      '• Докупи в первую очередь обувь и верхнюю одежду — они задают «дороговизну» образа и работают в ~70% выходов.\n' +
      '• Убери кричащие принты, добавь 2–3 базовых нейтральных вещи (чёрный, серый, бежевый).\n\n' +
      'Почему: дорогой вид считывается через монохром, чистые линии и качество ключевых вещей, а не через количество.'
    );
  if (q.includes('бесполезн') || q.includes('пробел'))
    return (
      'Бесполезными чаще оказываются вещи с высоким cost-per-wear: яркие single-use вещи под один повод и дубли базы.\n\n' +
      'Почему: если вещь не сочетается минимум с 3 другими, она не входит в ротацию и тянет аналитику вниз. ' +
      'Оставляй то, что собирает много образов.'
    );
  if (q.includes('цвет'))
    return (
      'Опираюсь на твой цветотип из профиля. Базу строй на нейтральных (чёрный/серый/бежевый), ' +
      'а характер добавляй 1–2 акцентами.\n\nПочему: нейтральная база сочетается со всем и выглядит дороже, ' +
      'а акцент делает образ запоминающимся без перегруза.'
    );
  if (q.includes('силуэт'))
    return (
      'Под твой тип фигуры лучше работают силуэты, которые уравновешивают пропорции: ' +
      'подчёркиваем сильные зоны, балансируем остальное.\n\nПочему: правильный силуэт визуально выстраивает ' +
      'пропорции 1:1.6 — это считывается как гармония.'
    );
  if (q.includes('макияж'))
    return (
      'Под твой стиль подойдёт аккуратный «здоровый» макияж: ровный тон, мягкие тёплые/холодные акценты под твой цветотип.\n\n' +
      'Почему: макияж должен поддерживать образ, а не спорить с ним. ⚠️ Это не медицинский совет.'
    );
  if (q.includes('причёск') || q.includes('волос'))
    return (
      'Причёска усилит образ, если повторит его настроение: чёткие линии — к минимализму, мягкие волны — к женственности.\n\n' +
      'Почему: форма причёски обрамляет лицо и задаёт первое впечатление сильнее, чем одежда.'
    );
  if (q.includes('5000'))
    return (
      'На 5000 ₽ максимум образов улучшит одна сильная база: качественные ботинки ИЛИ нейтральная верхняя одежда.\n\n' +
      'Почему: эти категории входят в большинство выходов, поэтому одна покупка «прокачивает» весь гардероб.'
    );
  if (q.includes('5 покуп') || q.includes('эффект'))
    return (
      'Топ-5 по эффекту обычно: 1) обувь-база, 2) верхняя одежда нейтрального цвета, 3) хорошо сидящие брюки, ' +
      '4) базовая рубашка/футболка премиального качества, 5) один акцентный аксессуар.\n\n' +
      'Почему: это «соединительные» вещи — они сочетаются со многими и поднимают средний уровень всех образов.'
    );
  if (q.includes('подчеркну'))
    return (
      'Подчёркивай сильные зоны (по типу фигуры из профиля), а противоположные — балансируй кроем и цветом.\n\n' +
      'Почему: акцент на сильном + баланс остального = ощущение пропорций и уверенности.'
    );
  if (q.includes('погод') || q.includes('повод') || q.includes('надеть') || q.includes('образ'))
    return (
      'Соберу образ под погоду и повод из твоих вещей: верх + низ + обувь + 1 акцент.\n\n' +
      'Например: нейтральный верх, тёмный низ, базовая обувь, один акцентный аксессуар.\n\n' +
      'Почему: такая формула выглядит собранно, расширяет силуэт в плечах и за счёт спокойной палитры читается дороже.'
    );

  return (
    'Я твой стилист-ассистент. Спроси про образ под повод, цвета, силуэты, уход или что докупить — ' +
    'и я объясню не только «что», но и «почему».'
  );
};

export class MockAIProvider implements AIProvider {
  readonly name = 'mock';
  async chat(req: AIChatRequest): Promise<AIChatResponse> {
    const lastUser = [...req.messages].reverse().find((m) => m.role === 'user');
    return { content: reply(lastUser?.content ?? ''), provider: this.name };
  }
}
